import { marked } from "marked";

/**
 * Export content as a printable PDF (opens in new window with print dialog).
 */
export function exportAsPDF(content, title = "Lyra Response") {
  const html = marked.parse(content);
  const win = window.open("", "_blank");
  win.document.write(`<!DOCTYPE html><html><head><title>${title}</title><style>
    body{font-family:'Georgia',serif;max-width:800px;margin:40px auto;padding:0 24px;color:#111;line-height:1.8;}
    h1,h2,h3{color:#1a1a2e;border-bottom:1px solid #eee;padding-bottom:6px;}
    code{background:#f4f4f4;padding:2px 6px;border-radius:4px;font-size:0.85em;}
    pre{background:#f4f4f4;padding:16px;border-radius:8px;overflow:auto;}
    blockquote{border-left:4px solid #6b8afd;margin:0;padding-left:16px;color:#555;}
    table{border-collapse:collapse;width:100%;}
    td,th{border:1px solid #ddd;padding:8px 12px;}
    th{background:#f0f4f8;}
    .header{display:flex;align-items:center;gap:12px;margin-bottom:32px;padding-bottom:16px;border-bottom:2px solid #6b8afd;}
    .footer{margin-top:40px;padding-top:12px;border-top:1px solid #eee;font-size:0.75rem;color:#999;}
    @media print{body{margin:0;}button{display:none;}}
  </style></head><body>
    <div class="header"><h1 style="margin:0;font-size:1.4rem;color:#1a1a2e;">◈ Lyra</h1><span style="color:#666;font-size:0.85rem;">AI Workspace</span></div>
    <h2>${title}</h2>${html}
    <div class="footer">Generated by Lyra · ${new Date().toLocaleDateString()}</div>
    <script>window.onload=()=>{window.print();}<\/script>
  </body></html>`);
  win.document.close();
}

/**
 * Export content as a downloadable markdown file.
 */
export function exportAsText(content, title = "lyra-response") {
  const blob = new Blob([content], { type: "text/markdown" });
  downloadBlob(blob, `${title.slice(0, 40).replace(/\s+/g, "-")}.md`);
}

/**
 * Download a Blob as a file.
 */
function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

// ── Study Mode: Flashcard Utilities ─────────────────────────────────────────

/**
 * Parse flashcards from Lyra's Study mode response.
 * Expects format: Q: ... / A: ...
 * @param {string} text - The AI response text
 * @returns {Array<{q: string, a: string}>}
 */
export function parseFlashcardsFromResponse(text) {
  const flashcards = [];

  // Pattern 1: Q: ... / A: ... (single line)
  const singleLineRegex = /Q:\s*(.+?)\s*\/\s*A:\s*(.+?)(?=\nQ:|$)/gs;
  for (const match of text.matchAll(singleLineRegex)) {
    flashcards.push({ q: match[1].trim(), a: match[2].trim() });
  }

  // Pattern 2: Multi-line Q/A blocks
  if (flashcards.length === 0) {
    const multiLineRegex = /\*?\*?Q(?:uestion)?:?\*?\*?\s*(.+?)[\n\r]+\s*\*?\*?A(?:nswer)?:?\*?\*?\s*(.+?)(?=\n\s*\*?\*?Q|$)/gs;
    for (const match of text.matchAll(multiLineRegex)) {
      flashcards.push({ q: match[1].trim(), a: match[2].trim() });
    }
  }

  return flashcards;
}

/**
 * Export flashcards as Anki-compatible CSV.
 * Can be directly imported into Anki via File → Import.
 * @param {Array<{q: string, a: string}>} flashcards
 */
export function exportAsAnkiCSV(flashcards) {
  if (!flashcards.length) return;

  const lines = flashcards.map(({ q, a }) => {
    // Escape quotes for CSV
    const escQ = q.replace(/"/g, '""');
    const escA = a.replace(/"/g, '""');
    return `"${escQ}","${escA}"`;
  });

  const csv = "Question,Answer\n" + lines.join("\n");
  const blob = new Blob([csv], { type: "text/csv;charset=utf-8;" });
  downloadBlob(blob, "lyra-flashcards.csv");
}

/**
 * Export content as JSON (useful for templates and data export).
 */
export function exportAsJSON(data, filename = "lyra-export") {
  const json = JSON.stringify(data, null, 2);
  const blob = new Blob([json], { type: "application/json" });
  downloadBlob(blob, `${filename}.json`);
}
